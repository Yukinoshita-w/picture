'use strict';
const esbuild = require('esbuild');
const fs = require('node:fs/promises');
const path = require('node:path');
const { pathToFileURL } = require('node:url');

async function build() {
  // Serve the vendor's own CSS locally: the app deliberately disallows inline style
  // sheets. Plugins normally inject <style> tags, so replace only that loader.
  const vendorRoot = path.dirname(require.resolve('@antv/x6/package.json'));
  const styles = ['style/raw.js', 'plugin/selection/style/raw.js', 'plugin/transform/style/raw.js', 'plugin/snapline/style/raw.js'];
  const css = await Promise.all(styles.map(async file => (await import(pathToFileURL(path.join(vendorRoot, 'es', file)).href)).content));
  await fs.writeFile('public/whiteboard.vendor.css', '/* AntV X6 3.1.8 · MIT · generated by npm run build */\n' + css.join('\n'));
  const licenses = [['@antv/x6', 'LICENSE'], ['tslib', 'LICENSE.txt'], ['lodash-es', 'LICENSE'], ['dom-align', 'LICENSE.md'], ['mousetrap', 'LICENSE'], ['utility-types', 'LICENSE']];
  const notices = await Promise.all(licenses.map(async ([name, file]) => {
    const location = path.join('node_modules', name);
    const manifest = JSON.parse(await fs.readFile(path.join(location, 'package.json'), 'utf8'));
    return name + ' ' + manifest.version + '\n' + await fs.readFile(path.join(location, file), 'utf8');
  }));
  await fs.writeFile('public/whiteboard.vendor.LICENSE.txt', 'Third-party notices for the bundled whiteboard editor\n\n' + notices.join('\n\n--------------------\n\n'));
  await esbuild.build({
    entryPoints: ['src/whiteboard.js'],
    bundle: true,
    minify: true,
    sourcemap: false,
    format: 'esm',
    target: ['chrome100', 'edge100', 'firefox102', 'safari16'],
    outfile: 'public/whiteboard.bundle.js',
    legalComments: 'linked',
    logLevel: 'info',
    plugins: [{ name: 'local-x6-styles', setup(build) {
      build.onResolve({ filter: /^\.\/css-loader$/ }, args => {
        if (args.resolveDir.replaceAll('\\', '/').endsWith('/x6/es/common')) return { path: path.resolve('src/x6-local-styles.mjs') };
      });
    } }]
  });
}
build().catch(error => { console.error(error); process.exitCode = 1; });

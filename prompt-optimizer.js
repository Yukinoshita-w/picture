const STRENGTH_RULES = {
  light: '本次优化强度：轻度润色。仅整理表达、语序和重复内容，使已有描述清晰连贯。不要新增原文未提及的环境、动作、构图、光影、材质、风格或负面约束；题材清单仅用于检查已有信息，不用于补齐字段。必要的平台语法转换和画布适配仍按通用规则执行。',
  standard: '本次优化强度：标准优化。保持原意，按题材补足必要的构图、光影、材质与视觉描述，只增加少量与主题一致的中性细节和相关负面约束。不扩展成新的场景，不堆砌全部字段。',
  rich: '本次优化强度：丰富细节。允许围绕原主题扩展协调的场景、空间层次、光影、色彩和材质细节，让画面更完整，但不添加无关主体，不改变明确要求；用户要求简洁时仍保持简洁。'
};

function buildOptimizationInstructions({ referenceCount, referenceGuidance = [], canvasSize, imageCount, strength = 'standard' }) {
  if (!Object.hasOwn(STRENGTH_RULES, strength)) throw new Error('不支持的优化强度');
  let instructions = OPTIMIZATION_RULES + '\n\n六、当前优化强度（决定补充范围，优先于题材清单中的补全建议）\n' + STRENGTH_RULES[strength];
  if (referenceCount) instructions += '\n用户另外提供了 ' + referenceCount + ' 张参考图，但本次请求不包含图片。保留原描述中的参考图编号、对应关系以及需要保留或修改的要素，不要虚构参考图片的内容或声称看过图片。';
  if (referenceGuidance?.length) {
    const lines = referenceGuidance.map((item, index) => {
      if (!item) return '';
      const parts = ['参考图' + (index + 1) + '（用途：' + (item.purpose || item.customPurpose || '未指定') + '）'];
      if (item.preserve) parts.push('需要保留：' + item.preserve);
      if (item.change) parts.push('需要修改：' + item.change);
      return parts.join('，');
    }).filter(Boolean);
    if (lines.length) instructions += '\n用户为参考图提供了以下文字说明。仅依据这些说明建立编号关系，不要声称看过图片：\n' + lines.join('\n');
  }
  if (canvasSize && !['default', 'auto'].includes(canvasSize)) {
    const ratios = { '256x256': '1:1', '512x512': '1:1', '1024x1024': '1:1', '1536x1024': '3:2', '1024x1536': '2:3', '1792x1024': '7:4', '1024x1792': '4:7' };
    instructions += '\n当前页面画布尺寸为 ' + canvasSize + '，比例为 ' + ratios[canvasSize] + '。按此画布组织构图，不输出相冲突的实际尺寸或比例。';
  } else instructions += '\n当前页面未指定固定画布比例；保留用户明确的比例意图，不擅自添加比例或输出尺寸。';
  if (imageCount) instructions += '\n当前页面请求生成 ' + imageCount + ' 张图片。这是输出图片张数，不是单张画面中的人物、动物或物体数量，不能因此增减主体。';
  return instructions;
}

